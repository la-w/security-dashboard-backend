using System.Globalization;
using Microsoft.CodeAnalysis.Sarif;
using Microsoft.EntityFrameworkCore;
using SecurityDashboard_Backend.DomainModel;
using SecurityDashboard_Backend.Utilities;

namespace SecurityDashboard_Backend.Services;

public class SarifImportService : ISarifImportService
{
    private readonly ILogger<SarifImportService> _logger;
    private readonly SecDashboardContext _context;

    private const FailureLevel
        _resultDefaultLevel =
            FailureLevel.Warning; // DefaultValue if not set, see https://github.com/microsoft/sarif-sdk/blob/ab7f7b1925e6657a00434c64d6d233c205b3fca7/src/Sarif/Autogenerated/Result.cs#L92

    public SarifImportService(ILogger<SarifImportService> logger, SecDashboardContext context)
    {
        _logger = logger;
        _context = context;
    }

    public async Task ImportAsync(SarifLog sarifLog, long pipelineId)
    {
        if (sarifLog.Runs == null || sarifLog.Runs.Count == 0)
            throw new ArgumentException("SarifLog must contain at least one run", nameof(sarifLog));

        var sarifTool = sarifLog.DetermineTool();

        if (sarifTool == null)
            throw new ArgumentException("SarifLog is from an unknown tool.", nameof(sarifLog));

        var pipelineRun = await _context.PipelineRuns.AsNoTracking().SingleOrDefaultAsync(p => p.PipelineId == pipelineId);

        if (pipelineRun == null)
            throw new ArgumentException($"PipelineRun #{pipelineId} was not found.", nameof(pipelineId));

        await ImportRules(sarifLog, sarifTool.Value);
        await ImportResults(sarifLog, sarifTool.Value, pipelineRun.Id);
    }

    private async Task ImportRules(SarifLog sarifLog, SarifTool sarifTool)
    {
        var rules = sarifLog.Runs.FirstOrDefault()?.Tool?.Driver?.Rules;

        if (rules == null)
            throw new ArgumentException("SarifLog does not contain rules.", nameof(sarifLog));

        var knownRules = await _context.ToolRules.Where(r => r.Tool == sarifTool).ToDictionaryAsync(r => r.RuleId, r => r);
        _logger.LogDebug("Loaded {RuleCount} known rules for tool {SarifTool}.", knownRules.Count, sarifTool);

        var totalRules = 0;
        var newRules = 0;

        foreach (var rule in rules)
        {
            if (string.IsNullOrEmpty(rule.Id))
            {
                _logger.LogWarning("Skipping rule without ID.");
                continue;
            }

            totalRules++;

            if (!knownRules.TryGetValue(rule.Id, out var toolRule))
            {
                newRules++;

                toolRule = new ToolRule
                {
                    Tool = sarifTool,
                    RuleId = rule.Id
                };

                await _context.ToolRules.AddAsync(toolRule);

                _logger.LogDebug("Importing new Rule [{RuleId}] for Tool {SarifTool}.", toolRule.RuleId, sarifTool);
            }

            toolRule.Name = rule.Name ?? rule.Id;
            toolRule.DefaultLevel = rule.DefaultConfiguration?.Level;
            toolRule.ShortDescription = rule.ShortDescription?.Text ?? rule.ShortDescription?.Markdown;
            toolRule.FullDescription = rule.FullDescription?.Text ?? rule.FullDescription?.Markdown;
            toolRule.HelpText = rule.Help?.Text ?? rule.Help?.Markdown;
            toolRule.HelpUri = rule.HelpUri?.ToString();

            if (sarifTool == SarifTool.OwaspDependencyCheck)
                ParseOwaspDependencyCheckRule(rule, toolRule);
        }

        await _context.SaveChangesAsync();

        _logger.LogInformation("{TotalCount} rules were imported / updated for Tool {SarifTool}. {NewRules} new rules imported.", totalRules,
            sarifTool, newRules);
    }

    private void ParseOwaspDependencyCheckRule(ReportingDescriptor rule, ToolRule toolRule)
    {
        var cvssProperties = new List<(string propertyName, string vectorName)>()
        {
            ("attackVector", "AV"),
            ("attackComplexity", "AC"),
            ("privilegesRequired", "PR"),
            ("userInteraction", "UI"),
            ("scope", "S"),
            ("confidentialityImpact", "C"),
            ("integrityImpact", "I"),
            ("availabilityImpact", "A")
        };

        // CVSSv3 Vector: CVSS:3.0/AV:N/AC:L/PR:N/UI:N/S:U/C:H/I:H/A:N
        var cvssVector = "CVSS:";

        if (rule.TryGetProperty("cvssv3_version", out var cvssVersionRaw))
        {
            switch (cvssVersionRaw)
            {
                case "_3_0":
                    cvssVector += "3.0";
                    break;
                case "_3_1":
                    cvssVector += "3.1";
                    break;
                default:
                    return;
            }
        }

        foreach (var (propertyName, vectorName) in cvssProperties)
        {
            if (rule.TryGetProperty($"cvssv3_{propertyName}", out var propertyValue) && !string.IsNullOrWhiteSpace(propertyValue))
                cvssVector += $"/{vectorName}:{propertyValue.Substring(0, 1)}";
            else return;
        }

        toolRule.CvssVector = cvssVector;
    }

    private async Task ImportResults(SarifLog sarifLog, SarifTool sarifTool, long pipelineRunId)
    {
        if (sarifTool != SarifTool.FluidAttacks)
        {
            if (await _context.ToolFindings.AsNoTracking().AnyAsync(f => f.Tool == sarifTool && f.PipelineRunId == pipelineRunId))
            {
                _logger.LogWarning("Findings for Tool {SarifTool} in PipelineRun #[{PipelineRunId}] were already imported.", sarifTool,
                    pipelineRunId);
                return;
            }
        }
        else
        {
            var importedFluidAttacksTypes = await _context.ToolFindings.AsNoTracking()
                .Where(f => f.Tool == sarifTool && f.PipelineRunId == pipelineRunId)
                .Select(f => f.DetectionType)
                .Distinct()
                .ToListAsync();

            var resultKinds = sarifLog.Results()
                .Select(r => r.TryGetProperty("kind", out var kind) ? kind : null)
                .Where(k => k != null)
                .Distinct()
                .ToList();

            // If SAST was imported but new results are only DAST
            if (!((importedFluidAttacksTypes.TrueForAll(t => t != DetectionType.DAST) && resultKinds.TrueForAll(k => k == "DAST"))
                  // or DAST was imported but new results are only SAST,SCA,SECRET
                  || (importedFluidAttacksTypes.TrueForAll(t => t == DetectionType.DAST) && resultKinds.TrueForAll(k => k != "DAST"))))
            {
                _logger.LogWarning("Findings for Tool {SarifTool} in PipelineRun #[{PipelineRunId}] were already imported.", sarifTool,
                    pipelineRunId);
                return;
            }
        }

        var totalResults = 0;
        var importedFindings = 0;

        var toolRules = await _context.ToolRules.AsNoTracking()
            .Where(r => r.Tool == sarifTool)
            .ToDictionaryAsync(r => r.RuleId, r => new { r.Id, r.DefaultLevel });

        foreach (var result in sarifLog.Results())
        {
            totalResults++;

            try
            {
                if (!toolRules.TryGetValue(result.RuleId, out var toolRule))
                {
                    _logger.LogWarning("Skipping result with unknown RuleId {RuleId}.", result.RuleId);
                    continue;
                }

                ToolFinding toolFinding = sarifTool switch
                {
                    SarifTool.FluidAttacks => ParseFluidAttacksResult(result, toolRule.DefaultLevel),
                    SarifTool.GitLeaks => ParseGitLeaksResult(result, toolRule.DefaultLevel),
                    SarifTool.OwaspDependencyCheck => ParseOwaspDependencyCheckResult(result, toolRule.DefaultLevel),
                    SarifTool.Semgrep => ParseSemgrepResult(result, toolRule.DefaultLevel),
                    SarifTool.Trivy => ParseTrivyResult(result, toolRule.DefaultLevel),
                    SarifTool.OwaspZap => ParseOwaspZapResult(result, toolRule.DefaultLevel),
                    _ => throw new ArgumentException("Unknown / Not implemented SarifTool", nameof(sarifTool))
                };

                toolFinding.ToolRuleId = toolRule.Id;
                toolFinding.Tool = sarifTool;
                toolFinding.PipelineRunId = pipelineRunId;
                await _context.ToolFindings.AddAsync(toolFinding);

                _logger.LogDebug("Parsed finding from {SarifTool}:\nPath: {Path}; Line: {Line}\n{RuleId}: {Description}",
                    sarifTool, toolFinding.Location, toolFinding.SnippetStartLine, result.RuleId, toolFinding.Description);

                importedFindings++;
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "Error while trying to import a result from {SarifTool}", sarifTool);
            }
        }

        await _context.SaveChangesAsync();

        _logger.LogInformation(
            "{ImportedFindings} / {TotalResults} Findings were imported. {SkippedResults} Findings could not be parsed and were skipped.",
            importedFindings, totalResults, totalResults - importedFindings);
    }

    private void ParseSharedResultData(Result result, FailureLevel? ruleDefaultLevel, ToolFinding toolFinding, bool mayHaveNoSnippet = false)
    {
        if (result.Level == _resultDefaultLevel)
            toolFinding.Level = ruleDefaultLevel ?? result.Level;
        else
            toolFinding.Level = result.Level;

        toolFinding.Description = result.Message?.Text ??
                                  result.Message?.Markdown ?? throw new ArgumentException("Result has no message.", nameof(result));

        var location = result.Locations?.FirstOrDefault()?.PhysicalLocation;

        if (location == null)
            throw new ArgumentException("Result has no location.", nameof(result));

        var locationUri = location.ArtifactLocation?.Uri;

        if (locationUri == null)
            throw new ArgumentException("Result has no location uri.", nameof(result));

        toolFinding.Location = locationUri.OriginalString;

        Region region;

        if (location.ContextRegion != null && location.ContextRegion.Snippet != null)
            region = location.ContextRegion;
        else if (location.Region != null && location.Region.Snippet != null)
            region = location.Region;
        else if (location.Region != null && location.Region.StartLine != 0 && location.Region.StartColumn != 0 && location.Region.EndLine != 0 &&
                 location.Region.EndColumn != 0) // Trivy does not provide a snippet
        {
            region = location.Region;
            region.Snippet = new ArtifactContent { Text = string.Empty };
        }
        else if (mayHaveNoSnippet)
        {
            region = new()
            {
                Snippet = new() { Text = "" },
                StartLine = 0,
                StartColumn = 0,
                EndLine = 0,
                EndColumn = 0
            };
        }
        else
            throw new ArgumentException("Result has no region.", nameof(result));

        toolFinding.Snippet = region.Snippet?.Text ??
                              region.Snippet?.Rendered?.Text ?? throw new ArgumentException("Result has no snippet.", nameof(result));
        toolFinding.SnippetStartLine = region.StartLine;
        toolFinding.SnippetStartColumn = region.StartColumn;
        toolFinding.SnippetEndLine = region.EndLine;
        toolFinding.SnippetEndColumn = region.EndColumn;
    }

    private FluidAttacksFinding ParseFluidAttacksResult(Result result, FailureLevel? ruleDefaultLevel)
    {
        var finding = new FluidAttacksFinding();

        ParseSharedResultData(result, ruleDefaultLevel, finding);

        if (result.TryGetProperty("cvss", out string cvssVector))
            finding.Cvss31Vector = cvssVector;

        if (result.TryGetProperty("cvss_v4", out string cvssV4Vector))
            finding.Cvss40Vector = cvssV4Vector;

        if (result.TryGetProperty("cwe_ids", out IEnumerable<string> cweIds))
            finding.CweIds = cweIds.ToList();

        if (result.Message?.TryGetProperty("cve", out IEnumerable<string> cves) == true)
            finding.SecurityAdvisories = cves.ToList();

        // TODO: Check if calculation of CVSS Score is available as library

        finding.Kind = result.GetProperty("kind");
        finding.Technique = result.GetProperty("technique");
        finding.SourceMethod = result.GetProperty("source_method");

        finding.DetectionType = finding.Kind switch
        {
            "SAST" => DetectionType.SAST,
            "DAST" => DetectionType.DAST,
            "SCA" => DetectionType.SCA,
            _ => DetectionType.SAST
        };

        var contextRegion = result.Locations.First().PhysicalLocation?.ContextRegion;

        if (contextRegion != null && contextRegion.TryGetProperty<int>("line", out var line))
            finding.Line = line;

        return finding;
    }

    private GitLeaksFinding ParseGitLeaksResult(Result result, FailureLevel? ruleDefaultLevel)
    {
        var finding = new GitLeaksFinding();

        ParseSharedResultData(result, ruleDefaultLevel, finding);

        finding.DetectionType = DetectionType.SECRET;

        var partialFingerprints = result.PartialFingerprints;

        if (partialFingerprints == null)
            throw new ArgumentException("Result has no partialFingerprints.", nameof(result));

        if (partialFingerprints.TryGetValue("commitSha", out var commitSha) && commitSha != null)
            finding.CommitHash = commitSha;
        else
            throw new ArgumentException("Result has no CommitHash.", nameof(result));

        if (partialFingerprints.TryGetValue("email", out var email) && email != null)
            finding.Email = email;
        else
            throw new ArgumentException("Result has no Email.", nameof(result));

        if (partialFingerprints.TryGetValue("author", out var author) && author != null)
            finding.Author = author;
        else
            throw new ArgumentException("Result has no Author.", nameof(result));

        if (partialFingerprints.TryGetValue("date", out var date) && date != null)
            finding.CommitDate = DateTime.Parse(date, null, DateTimeStyles.RoundtripKind);
        else
            throw new ArgumentException("Result has no CommitDate.", nameof(result));

        if (partialFingerprints.TryGetValue("commitMessage", out var commitMessage) && commitMessage != null)
            finding.CommitMessage = commitMessage;
        else
            throw new ArgumentException("Result has no CommitMessage.", nameof(result));

        return finding;
    }

    private OwaspDependencyCheckFinding ParseOwaspDependencyCheckResult(Result result, FailureLevel? ruleDefaultLevel)
    {
        var finding = new OwaspDependencyCheckFinding();

        ParseSharedResultData(result, ruleDefaultLevel, finding, true);

        finding.DetectionType = DetectionType.SCA;

        if (result.RuleId.StartsWith("CVE") || result.RuleId.StartsWith("GHSA") || result.RuleId.StartsWith("NSWG"))
            finding.SecurityAdvisories = [result.RuleId];

        return finding;
    }

    private SemgrepFinding ParseSemgrepResult(Result result, FailureLevel? ruleDefaultLevel)
    {
        var finding = new SemgrepFinding();

        ParseSharedResultData(result, ruleDefaultLevel, finding);

        finding.DetectionType = DetectionType.SAST;

        // Semgrep has no additional data

        return finding;
    }

    private TrivyFinding ParseTrivyResult(Result result, FailureLevel? ruleDefaultLevel)
    {
        var finding = new TrivyFinding();

        ParseSharedResultData(result, ruleDefaultLevel, finding);

        if (result.RuleId.StartsWith("CVE") || result.RuleId.StartsWith("GHSA") || result.RuleId.StartsWith("NSWG"))
        {
            finding.DetectionType = DetectionType.SCA;
            finding.SecurityAdvisories = [result.RuleId];
        }
        else
        {
            finding.DetectionType = DetectionType.SECRET;
        }

        return finding;
    }

    private OwaspZapFinding ParseOwaspZapResult(Result result, FailureLevel? ruleDefaultLevel)
    {
        var finding = new OwaspZapFinding();

        ParseSharedResultData(result, ruleDefaultLevel, finding);

        finding.DetectionType = DetectionType.DAST;

        finding.Attack = result.Locations.FirstOrDefault()?.GetProperty("attack") ??
                         throw new ArgumentException("Result has no attack-property.", nameof(result));
        finding.WebRequest = result.WebRequest.GetStringRepresentation();
        finding.WebResponse = result.WebResponse.GetStringRepresentation();

        var rule = result.Run.Tool.Driver.GetRuleById(result.RuleId);

        if (rule.Relationships?.Any(r => !string.IsNullOrEmpty(r.Target?.Id) && r.Target?.ToolComponent?.Name == "CWE") == true)
        {
            finding.CweIds = rule.Relationships
                .Where(r => !string.IsNullOrEmpty(r.Target?.Id) && r.Target?.ToolComponent?.Name == "CWE")
                .Select(r => $"CWE-{r.Target.Id}")
                .ToList();
        }

        return finding;
    }
}
